;---------------------------------------------------------------------
; LUT for octave changes
;---------------------------------------------------------------------
;
; Values here are used as an additive to offset the below note frequency
; table in order to select an octave. Strangely, this table is 6 entries,
; but the frequency table is only 4 octaves, which means the last 2 entries
; in this table are useless.
