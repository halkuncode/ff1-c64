    RTS

Play:
    BEQ Resume
    JMP AUDIOIN
Resume:
    LDA CHAN_SQ1 + ch_freq+1 ; $BF
    BMI Sq1_NoFreqChange
    LDA CHAN_SQ1 + ch_vol    ; $BC
    ORA #%01110000           ; #$70
    STA $4000
    LDA #%01111111 ; #$7F
    STA $4001
    LDA CHAN_SQ1 + ch_freq   ; $BE
    STA $4002
    LDA CHAN_SQ1 + ch_freq+1 ; $BF
    STA $4003
    LDA #$80
    STA CHAN_SQ1 + ch_freq+1 ; $BF
    JMP sq1_done
Sq1_NoFreqChange:
    LDA CHAN_SQ1 + ch_vol    ; $BC
    ORA #%01110000           ; #$70
    STA $4000
    LDA #%01111111           ; #$7F
    STA $4001
